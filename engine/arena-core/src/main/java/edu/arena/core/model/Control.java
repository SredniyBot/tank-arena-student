package edu.arena.core.model;

import java.util.Objects;

/**
 * Управление танком: движение корпуса, наведение башни, выстрел и щит.
 *
 * <p>Начало координат — левый верхний угол арены; X растёт вправо, Y — вниз. Расстояния измеряются
 * в единицах игрового мира, углы — в радианах. Положительный поворот на экране идёт по часовой
 * стрелке. Команда описывает намерение: столкновения, скорость поворота башни и таймеры
 * ограничивают результат.
 *
 * <p>В сетевой арене решения принимаются на общих тактах управления. Размер P берите из {@code
 * view.timing().controlPeriodTicks()}: снимок N открывает окно ответа до N + P, а принятое решение
 * удерживается на физических шагах от N + P включительно до N + 2P исключительно. Все поля команды
 * проверяются на каждом из этих шагов. Ранний ответ не выполняется раньше. На один такт принимается
 * одно решение; повтор пакета не продлевает действие. Без следующего решения управление станет
 * нейтральным. После смерти команды сбрасываются. SDK соблюдает расписание; уже выпущенные снаряды
 * и таймеры продолжают действовать.
 *
 * <p>Физические скорости и длительности берите из {@code view.rules()}, расписание команды — из
 * {@code view.timing()}. Преподаватель может изменить физические условия во время боя. Изменение
 * правил не требует нового экземпляра бота. Длительность команды в игровых секундах равна P /
 * tickRate; реальное окно ответа зависит от темпа сервера.
 *
 * @param throttle доля скорости движения, конечное число от {@code -1} до {@code 1}: {@code 1} —
 *     вперёд вдоль корпуса со скоростью {@code rules.moveSpeed()}, {@code -1} — назад с той же
 *     скоростью, {@code 0} — без перемещения. {@code 0.5} задаёт половину скорости. Это скорость, а
 *     не ускорение: инерции нет. Движение использует направление корпуса после поворота этого шага;
 *     стены и другие танки могут его ограничить. Значения за диапазоном не обрезаются, а
 *     отвергаются конструктором.
 * @param turn доля угловой скорости корпуса, конечное число от {@code -1} до {@code 1}: {@code 1} —
 *     по часовой стрелке, {@code -1} — против, {@code 0} — сохранить направление. За шаг угол
 *     изменяется на {@code turn * rules.turnSpeed() / rules.tickRate()}. Это не целевой угол;
 *     поворачивать можно на месте и во время движения. Направление башни задаётся отдельно через
 *     {@code aim}. Значения за диапазоном не обрезаются, а отвергаются конструктором.
 * @param aim абсолютная точка мира, к которой поворачивается башня, например {@code new Vec2(800,
 *     400)}. Это не угол и не вектор смещения. Башня поворачивается кратчайшим путём не быстрее
 *     {@code rules.turretSpeed()} радиан за игровую секунду. Точка, совпадающая с текущим центром
 *     своего танка (расстояние меньше {@code 1e-12}), сохраняет направление башни. {@code null}
 *     запрещён; {@link Vec2} допускает только конечные координаты. Сервер дополнительно требует
 *     {@code abs(x) <= 4 * map.width()} и {@code abs(y) <= 4 * map.height()}; точка может
 *     находиться за краем поля.
 * @param fire удерживаемый запрос стрельбы на всё окно команды. {@code false} не запрашивает
 *     выстрел. На каждом физическом шаге {@code true} выпускает не более одного снаряда, если
 *     оружие готово и танк не защищён щитом или защитой появления. Одна команда может дать
 *     несколько выстрелов, если внутри её окна успевает завершиться перезарядка. Таймер оружия
 *     уменьшается перед проверкой: значение {@code cooldownTicks() <= 1} непосредственно перед
 *     переходом позволяет стрелять в этом переходе. Таймер из более раннего снимка N не гарантирует
 *     состояние на N + P. Снаряд летит по фактическому направлению башни после её поворота: сервер
 *     не ждёт точного наведения. Переключать {@code false -> true} не требуется. Удерживаемый
 *     запрос может сработать после готовности внутри окна; за его пределами отдельной очереди нет.
 * @param shield удерживаемый запрос включения щита на всё окно команды. На каждом физическом шаге
 *     {@code true} включает щит, если таймер перед переходом {@code shieldCooldownTicks() <= 1};
 *     защита действует уже на шаге включения. Длительность равна {@code
 *     rules.shieldDurationTicks()}, включая этот шаг, а перезарядка начинается с момента включения
 *     и равна {@code rules.shieldCooldownTicks()}. Удерживаемое {@code true} снова включает щит
 *     после готовности. {@code false} не отменяет уже активный щит. Защищённый танк может двигаться
 *     и наводиться, но не может стрелять; при одновременных {@code fire=true} и успешном включении
 *     щита приоритет имеет щит. За пределами окна команды отдельной очереди запросов нет. Защиту
 *     появления сервер назначает сам.
 */
public record Control(double throttle, double turn, Vec2 aim, boolean fire, boolean shield) {
    /**
     * Создаёт команду без изменения или автоматического ограничения переданных значений.
     *
     * @throws IllegalArgumentException если throttle или turn не конечны либо вне [-1, 1]
     * @throws NullPointerException если aim равен null
     */
    public Control {
        if (!Double.isFinite(throttle)
                || Math.abs(throttle) > 1
                || !Double.isFinite(turn)
                || Math.abs(turn) > 1) {
            throw new IllegalArgumentException("Throttle and turn must be finite values in [-1,1]");
        }
        Objects.requireNonNull(aim, "aim");
    }

    /** Создаёт команду с {@code shield=false}; остальные поля имеют ту же семантику. */
    public Control(double throttle, double turn, Vec2 aim, boolean fire) {
        this(throttle, turn, aim, fire, false);
    }

    /**
     * Не двигаться, не поворачивать корпус, не стрелять и не запрашивать щит; наводиться на aim.
     * Точка, совпадающая с положением танка при исполнении, сохраняет направление башни. При
     * отложенном исполнении {@code view.me().position()} может быть уже позади танка: башня тогда
     * повернётся к старой точке.
     *
     * @param aim абсолютная точка прицела с теми же ограничениями, что в конструкторе
     * @return команда {@code new Control(0, 0, aim, false, false)}
     */
    public static Control idle(Vec2 aim) {
        return new Control(0, 0, aim, false);
    }
}
